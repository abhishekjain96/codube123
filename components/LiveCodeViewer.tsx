"use client";

import { useMemo, useState } from "react";
import { Check, Copy, Download, FileCode, FileJson, FileText, Folder, FolderOpen, Layers, Terminal, Zap } from "lucide-react";
import JSZip from "jszip";
import type { Section, SiteDoc } from "./SiteRenderer";

type FileItem = {
  path: string;
  name: string;
  folder: string;
  language: "typescript" | "json" | "css" | "javascript";
  content: string;
};

export default function LiveCodeViewer({
  doc,
  onOpenFullStudio,
}: {
  doc: SiteDoc | null;
  onOpenFullStudio?: () => void;
}) {
  const [activePath, setActivePath] = useState("app/page.tsx");
  const [copied, setCopied] = useState(false);
  const [zipping, setZipping] = useState(false);

  const files = useMemo<FileItem[]>(() => {
    if (!doc) return [];

    const brand = doc.brand || "CodubeApp";
    const primary = doc.theme?.accent || "#f97316";
    const secondary = doc.theme?.accent2 || "#8b5cf6";
    const isDark = doc.theme?.dark ?? true;
    const font = doc.theme?.font || "Inter";

    // Gather active sections
    const activePage = doc.pages?.[0] || { slug: "home", name: "Home", sections: doc.sections || [] };
    const sections: Section[] = activePage.sections || [];

    const generatedFiles: FileItem[] = [];

    // 1. app/page.tsx
    const sectionImports = Array.from(new Set(sections.map((s) => s.type))).map((type) => {
      const name = type.charAt(0).toUpperCase() + type.slice(1).replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `import ${name} from "@/components/${name}";`;
    });

    const sectionJSX = sections.map((s, idx) => {
      const name = s.type.charAt(0).toUpperCase() + s.type.slice(1).replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `        <${name} key="${idx}" title="${(s.title || "").replace(/"/g, '\\"')}" />`;
    });

    generatedFiles.push({
      path: "app/page.tsx",
      name: "page.tsx",
      folder: "app",
      language: "typescript",
      content: `// Production Next.js App Router Page
// Generated by Codube AI & REA
import Navbar from "@/components/Navbar";
${sectionImports.join("\n")}
import Footer from "@/components/Footer";

export default function HomePage() {
  return (
    <div className="min-h-screen ${isDark ? "bg-[#06060c] text-white" : "bg-white text-slate-900"} selection:bg-[${primary}] selection:text-white">
      <Navbar brand="${brand}" />
      <main className="space-y-24 pb-20">
${sectionJSX.join("\n")}
      </main>
      <Footer brand="${brand}" />
    </div>
  );
}
`,
    });

    // 2. app/layout.tsx
    generatedFiles.push({
      path: "app/layout.tsx",
      name: "layout.tsx",
      folder: "app",
      language: "typescript",
      content: `import type { Metadata } from "next";
import { Inter } from "next/font/google";
import "./globals.css";

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "${brand} — Built with Codube REA",
  description: "Next-generation web application engineered with high-performance responsive UI.",
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en" className="${isDark ? "dark" : ""}">
      <body className={inter.className}>{children}</body>
    </html>
  );
}
`,
    });

    // 3. app/globals.css
    generatedFiles.push({
      path: "app/globals.css",
      name: "globals.css",
      folder: "app",
      language: "css",
      content: `@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
  --primary: ${primary};
  --secondary: ${secondary};
}

html {
  scroll-behavior: smooth;
}

body {
  overflow-x: hidden;
}
`,
    });

    // 4. components/Navbar.tsx
    const navLinks = doc.navbar?.links || ["Features", "Solutions", "Pricing", "About"];
    generatedFiles.push({
      path: "components/Navbar.tsx",
      name: "Navbar.tsx",
      folder: "components",
      language: "typescript",
      content: `"use client";

import Link from "next/link";
import { useState } from "react";
import { Menu, X, Sparkles } from "lucide-react";

export default function Navbar({ brand }: { brand: string }) {
  const [open, setOpen] = useState(false);

  return (
    <header className="sticky top-0 z-50 border-b border-white/[0.08] bg-[#06060c]/80 backdrop-blur-xl">
      <div className="mx-auto flex h-16 max-w-7xl items-center justify-between px-4 sm:px-6">
        <Link href="/" className="flex items-center gap-2 text-lg font-black tracking-tight text-white">
          <span className="flex h-8 w-8 items-center justify-center rounded-xl bg-gradient-to-tr from-[${primary}] to-[${secondary}] text-white shadow-lg">
            <Sparkles size={16} />
          </span>
          <span>{brand}</span>
        </Link>

        <nav className="hidden items-center gap-8 md:flex">
          ${navLinks
            .map(
              (l) => `<Link href="#${l.toLowerCase()}" className="text-sm font-medium text-slate-300 transition hover:text-white">
            ${l}
          </Link>`
            )
            .join("\n          ")}
        </nav>

        <div className="hidden items-center gap-4 md:flex">
          <Link href="/login" className="text-sm font-medium text-slate-300 hover:text-white">
            Sign In
          </Link>
          <Link
            href="/signup"
            className="rounded-xl bg-gradient-to-r from-[${primary}] to-[${secondary}] px-4 py-2 text-sm font-semibold text-white shadow-lg shadow-[${primary}]/30 transition hover:opacity-90"
          >
            Get Started
          </Link>
        </div>

        <button
          onClick={() => setOpen(!open)}
          className="rounded-lg p-2 text-slate-400 hover:bg-white/10 md:hidden"
        >
          {open ? <X size={20} /> : <Menu size={20} />}
        </button>
      </div>
    </header>
  );
}
`,
    });

    // 5. Individual section components
    for (const sec of sections) {
      const typeName = sec.type.charAt(0).toUpperCase() + sec.type.slice(1).replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      const fileName = `${typeName}.tsx`;
      if (generatedFiles.some((f) => f.name === fileName)) continue;

      const title = sec.title || `${typeName} Section`;
      const subtitle = sec.subtitle || sec.text || "Experience precision-crafted components designed for speed.";
      const cta = sec.cta || "Get Started";

      generatedFiles.push({
        path: `components/${fileName}`,
        name: fileName,
        folder: "components",
        language: "typescript",
        content: `"use client";

import { ArrowRight, CheckCircle2, Sparkles, Shield, Zap } from "lucide-react";

export default function ${typeName}({ title = "${title.replace(/"/g, '\\"')}" }: { title?: string }) {
  return (
    <section className="relative px-4 sm:px-6 lg:px-8 py-16">
      <div className="mx-auto max-w-7xl">
        <div className="mx-auto max-w-3xl text-center">
          <span className="inline-flex items-center gap-1.5 rounded-full border border-[${primary}]/30 bg-[${primary}]/10 px-3 py-1 text-xs font-semibold text-[${primary}]">
            <Sparkles size={12} />
            Reverse-Engineered Architecture
          </span>
          <h2 className="mt-4 text-3xl font-extrabold tracking-tight sm:text-5xl text-white">
            {title}
          </h2>
          <p className="mt-4 text-base text-slate-400 sm:text-lg">
            ${subtitle.replace(/"/g, '\\"')}
          </p>
        </div>

        <div className="mt-12 flex justify-center">
          <button className="flex items-center gap-2 rounded-xl bg-gradient-to-r from-[${primary}] to-[${secondary}] px-6 py-3 font-semibold text-white shadow-xl shadow-[${primary}]/25 transition hover:scale-105">
            <span>${cta}</span>
            <ArrowRight size={16} />
          </button>
        </div>
      </div>
    </section>
  );
}
`,
      });
    }

    // 6. components/Footer.tsx
    generatedFiles.push({
      path: "components/Footer.tsx",
      name: "Footer.tsx",
      folder: "components",
      language: "typescript",
      content: `import Link from "next/link";

export default function Footer({ brand }: { brand: string }) {
  return (
    <footer className="border-t border-white/[0.08] bg-[#040408] py-12 text-slate-400">
      <div className="mx-auto max-w-7xl px-4 sm:px-6 flex flex-col sm:flex-row items-center justify-between gap-4">
        <p className="text-sm">© {new Date().getFullYear()} {brand}. Engineered with Codube REA.</p>
        <div className="flex gap-6 text-sm">
          <Link href="#privacy" className="hover:text-white">Privacy</Link>
          <Link href="#terms" className="hover:text-white">Terms</Link>
          <Link href="#contact" className="hover:text-white">Contact</Link>
        </div>
      </div>
    </footer>
  );
}
`,
    });

    // 7. tailwind.config.js
    generatedFiles.push({
      path: "tailwind.config.js",
      name: "tailwind.config.js",
      folder: "root",
      language: "javascript",
      content: `/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: "class",
  content: [
    "./app/**/*.{js,ts,jsx,tsx,mdx}",
    "./components/**/*.{js,ts,jsx,tsx,mdx}",
  ],
  theme: {
    extend: {
      colors: {
        primary: "${primary}",
        secondary: "${secondary}",
      },
    },
  },
  plugins: [],
};
`,
    });

    // 8. package.json
    generatedFiles.push({
      path: "package.json",
      name: "package.json",
      folder: "root",
      language: "json",
      content: JSON.stringify(
        {
          name: brand.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
          version: "0.1.0",
          private: true,
          scripts: {
            dev: "next dev",
            build: "next build",
            start: "next start",
          },
          dependencies: {
            next: "^15.0.0",
            react: "^19.0.0",
            "react-dom": "^19.0.0",
            "lucide-react": "^1.52.0",
          },
          devDependencies: {
            typescript: "^5",
            tailwindcss: "^4",
            "@types/node": "^20",
            "@types/react": "^19",
          },
        },
        null,
        2
      ),
    });

    // 9. site.config.json
    generatedFiles.push({
      path: "site.config.json",
      name: "site.config.json",
      folder: "root",
      language: "json",
      content: JSON.stringify(
        {
          brand,
          theme: { primary, secondary, dark: isDark, font },
          sectionsCount: sections.length,
          generatedAt: new Date().toISOString(),
          engine: "Codube REA (Reverse Engineering Architecture)",
        },
        null,
        2
      ),
    });

    return generatedFiles;
  }, [doc]);

  const activeFile = files.find((f) => f.path === activePath) || files[0];

  function copyCode() {
    if (!activeFile) return;
    navigator.clipboard.writeText(activeFile.content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  function downloadSingleFile() {
    if (!activeFile) return;
    const blob = new Blob([activeFile.content], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = activeFile.name;
    a.click();
    URL.revokeObjectURL(url);
  }

  async function downloadZip() {
    setZipping(true);
    try {
      const zip = new JSZip();
      for (const f of files) {
        zip.file(f.path, f.content);
      }
      const blob = await zip.generateAsync({ type: "blob" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `${(doc?.brand || "codube-project").toLowerCase().replace(/[^a-z0-9]+/g, "-")}-nextjs-bundle.zip`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (e) {
      console.error(e);
    } finally {
      setZipping(false);
    }
  }

  const grouped = useMemo(() => {
    const map = new Map<string, FileItem[]>();
    for (const f of files) {
      const list = map.get(f.folder) || [];
      list.push(f);
      map.set(f.folder, list);
    }
    return map;
  }, [files]);

  return (
    <div className="flex h-full min-h-[620px] flex-col overflow-hidden rounded-2xl border border-white/10 bg-[#07070f] shadow-2xl">
      {/* Top Studio Control Bar */}
      <div className="flex h-12 shrink-0 items-center justify-between border-b border-white/[0.08] bg-[#0c0c16] px-4">
        <div className="flex items-center gap-2">
          <div className="flex gap-1.5">
            <span className="h-3 w-3 rounded-full bg-rose-500/80" />
            <span className="h-3 w-3 rounded-full bg-amber-500/80" />
            <span className="h-3 w-3 rounded-full bg-emerald-500/80" />
          </div>
          <span className="ml-3 flex items-center gap-1.5 text-xs font-semibold text-slate-300">
            <Terminal size={14} className="text-orange-400" />
            Codube Code Studio — Next.js 15 App Router
          </span>
          <span className="rounded-full bg-white/[0.06] px-2 py-0.5 text-[10px] font-medium text-slate-400">
            {files.length} Production Files
          </span>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={copyCode}
            className="flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2.5 py-1 text-xs font-medium text-slate-300 transition hover:bg-white/10 hover:text-white"
          >
            {copied ? <Check size={13} className="text-emerald-400" /> : <Copy size={13} />}
            <span>{copied ? "Copied" : "Copy File"}</span>
          </button>

          <button
            onClick={downloadSingleFile}
            className="flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2.5 py-1 text-xs font-medium text-slate-300 transition hover:bg-white/10 hover:text-white"
          >
            <Download size={13} />
            <span>Download File</span>
          </button>

          <button
            onClick={downloadZip}
            disabled={zipping}
            className="btn-shine flex items-center gap-1.5 rounded-lg bg-gradient-to-r from-violet-600 to-indigo-600 px-3 py-1 text-xs font-semibold text-white shadow-md shadow-violet-600/30 transition hover:opacity-90 disabled:opacity-50"
          >
            <Download size={13} />
            <span>{zipping ? "Packaging..." : "Export ZIP Bundle"}</span>
          </button>

          {onOpenFullStudio && (
            <button
              onClick={onOpenFullStudio}
              className="flex items-center gap-1.5 rounded-lg border border-orange-500/30 bg-orange-500/10 px-2.5 py-1 text-xs font-medium text-orange-300 transition hover:bg-orange-500/20"
            >
              <Zap size={13} />
              <span>Full Exporter</span>
            </button>
          )}
        </div>
      </div>

      {/* Main split: File Tree + Code Display */}
      <div className="grid min-h-0 flex-1 grid-cols-1 md:grid-cols-[240px_1fr]">
        {/* Left: Tree */}
        <aside className="border-r border-white/[0.08] bg-[#090912] p-3 overflow-y-auto">
          <div className="mb-2 flex items-center justify-between px-2 text-[11px] font-bold uppercase tracking-wider text-slate-500">
            <span>Project Explorer</span>
            <Layers size={12} />
          </div>

          <div className="space-y-4">
            {Array.from(grouped.entries()).map(([folder, items]) => (
              <div key={folder}>
                <div className="flex items-center gap-1.5 px-2 py-1 text-[11px] font-semibold text-slate-400">
                  <FolderOpen size={13} className="text-violet-400" />
                  <span>{folder}</span>
                </div>
                <div className="mt-0.5 space-y-0.5">
                  {items.map((item) => {
                    const isActive = item.path === activePath;
                    return (
                      <button
                        key={item.path}
                        onClick={() => setActivePath(item.path)}
                        className={`flex w-full items-center gap-2 rounded-lg px-3 py-1.5 text-left text-xs transition ${
                          isActive
                            ? "bg-violet-600/20 font-semibold text-violet-300 ring-1 ring-violet-500/40"
                            : "text-slate-400 hover:bg-white/[0.04] hover:text-slate-200"
                        }`}
                      >
                        {item.name.endsWith(".json") ? (
                          <FileJson size={13} className="text-amber-400 shrink-0" />
                        ) : item.name.endsWith(".css") ? (
                          <FileCode size={13} className="text-emerald-400 shrink-0" />
                        ) : (
                          <FileCode size={13} className="text-sky-400 shrink-0" />
                        )}
                        <span className="truncate">{item.name}</span>
                      </button>
                    );
                  })}
                </div>
              </div>
            ))}
          </div>
        </aside>

        {/* Right: Code Editor view */}
        <main className="flex flex-col min-h-0 bg-[#05050a] overflow-hidden">
          {/* File Tab Bar */}
          <div className="flex h-10 items-center border-b border-white/[0.06] bg-[#080812] px-4 text-xs">
            <span className="flex items-center gap-2 font-mono text-slate-300">
              <span className="h-2 w-2 rounded-full bg-violet-400" />
              {activeFile?.path}
            </span>
          </div>

          {/* Code text with line numbers */}
          <div className="flex-1 overflow-auto p-4 font-mono text-xs leading-relaxed text-slate-200">
            {activeFile?.content.split("\n").map((line, idx) => (
              <div key={idx} className="flex hover:bg-white/[0.02]">
                <span className="w-10 shrink-0 select-none text-right pr-4 text-slate-600 font-mono text-[11px]">
                  {idx + 1}
                </span>
                <span className="flex-1 whitespace-pre">{line || " "}</span>
              </div>
            ))}
          </div>
        </main>
      </div>
    </div>
  );
}
