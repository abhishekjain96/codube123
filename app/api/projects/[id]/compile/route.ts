import { NextRequest, NextResponse } from "next/server";
import { getProjectById } from "@/lib/serverStore";

export async function POST(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;
  const project = getProjectById(id);
  if (!project) {
    return NextResponse.json({ error: "Project not found" }, { status: 404 });
  }

  const files = [
    {
      path: "package.json",
      content: JSON.stringify(
        {
          name: (project.brand || "codube-site").toLowerCase().replace(/[^a-z0-9]+/g, "-"),
          version: "0.1.0",
          private: true,
          scripts: {
            dev: "next dev",
            build: "next build",
            start: "next start",
          },
          dependencies: {
            next: "^14.2.0",
            react: "^18.3.0",
            "react-dom": "^18.3.0",
            "lucide-react": "^0.400.0",
          },
          devDependencies: {
            tailwindcss: "^3.4.0",
            typescript: "^5.0.0",
            "@types/node": "^20.0.0",
            "@types/react": "^18.3.0",
          },
        },
        null,
        2
      ),
    },
    {
      path: "app/page.tsx",
      content: `export default function Page() {\n  return (\n    <main className="min-h-screen bg-slate-950 text-white p-8">\n      <h1 className="text-4xl font-bold">${project.brand || project.heading}</h1>\n      <p className="mt-4 text-slate-400">${project.subheading || project.idea}</p>\n    </main>\n  );\n}\n`,
    },
    {
      path: "README.md",
      content: `# ${project.brand || project.heading}\n\nGenerated by Codube.\n\n## Getting Started\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
    },
  ];

  return NextResponse.json({
    reply: "Production code files generated successfully.",
    files,
    project,
  });
}
